/**
 * Fetch authenticated user's YouTube Channel details
 */
export async function fetchMyChannel(accessToken: string): Promise<ChannelInfo> {
  const url = 'https://www.googleapis.com/youtube/v3/channels?part=snippet,statistics,brandingSettings&mine=true';
  const response = await fetch(url, {
    headers: {
      Authorization: `Bearer ${accessToken}`,
      Accept: 'application/json',
    },
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    throw new Error(
      errorData.error?.message || `Failed to fetch YouTube channel (${response.status})`
    );
  }

  const data = await response.json();
  if (!data.items || data.items.length === 0) {
    throw new Error('No YouTube channel found for this Google account. Please create a channel on YouTube first.');
  }

  const item = data.items[0];
  const snippet = item.snippet || {};
  const stats = item.statistics || {};
  const branding = item.brandingSettings || {};

  return {
    id: item.id,
    title: snippet.title || 'My YouTube Channel',
    description: snippet.description || '',
    customUrl: snippet.customUrl,
    avatarUrl: snippet.thumbnails?.high?.url || snippet.thumbnails?.default?.url || DEMO_CHANNEL.avatarUrl,
    bannerUrl: branding.image?.bannerExternalUrl || DEMO_CHANNEL.bannerUrl,
    subscriberCount: stats.subscriberCount || 0,
    viewCount: stats.viewCount || 0,
    videoCount: stats.videoCount || 0,
    country: snippet.country,
    isDemo: false,
  };
}

/**
 * Fetch authenticated channel's recent videos
 */
export async function fetchChannelVideos(accessToken: string): Promise<YouTubeVideo[]> {
  try {
    // 1. Get uploads playlist ID
    const channelRes = await fetch(
      'https://www.googleapis.com/youtube/v3/channels?part=contentDetails&mine=true',
      {
        headers: { Authorization: `Bearer ${accessToken}` },
      }
    );
    if (!channelRes.ok) return DEMO_VIDEOS;
    const channelData = await channelRes.json();
    const uploadsPlaylistId = channelData.items?.[0]?.contentDetails?.relatedPlaylists?.uploads;

    if (!uploadsPlaylistId) return DEMO_VIDEOS;

    // 2. Fetch playlist items
    const playlistRes = await fetch(
      `https://www.googleapis.com/youtube/v3/playlistItems?part=snippet,status&playlistId=${uploadsPlaylistId}&maxResults=10`,
      {
        headers: { Authorization: `Bearer ${accessToken}` },
      }
    );
    if (!playlistRes.ok) return DEMO_VIDEOS;
    const playlistData = await playlistRes.json();

    const videos: YouTubeVideo[] = (playlistData.items || []).map((item: any) => ({
      id: item.snippet.resourceId.videoId,
      title: item.snippet.title,
      description: item.snippet.description,
      publishedAt: item.snippet.publishedAt,
      thumbnailUrl:
        item.snippet.thumbnails?.maxres?.url ||
        item.snippet.thumbnails?.high?.url ||
        item.snippet.thumbnails?.medium?.url,
      privacyStatus: item.status?.privacyStatus || 'public',
      isAutoGenerated: false,
    }));

    return videos.length > 0 ? videos : DEMO_VIDEOS;
  } catch (err) {
    console.warn('Error fetching real channel videos, falling back to cached/demo:', err);
    return DEMO_VIDEOS;
  }
}

/**
 * Upload a video file to YouTube via Resumable Upload
 */
export async function uploadVideoToYouTube(
  accessToken: string,
  videoBlob: Blob,
  metadata: {
    title: string;
    description: string;
    tags?: string[];
    privacy?: 'public' | 'unlisted' | 'private';
    categoryId?: string;
  },
  onProgress?: (percent: number) => void
): Promise<{ videoId: string; watchUrl: string }> {
  // Step 1: Initiate resumable session
  const initUrl = 'https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status';

  const bodyData = {
    snippet: {
      title: metadata.title,
      description: metadata.description,
      tags: metadata.tags || ['AutoTube', 'AI', 'VoiceToVideo'],
      categoryId: metadata.categoryId || '28',
    },
    status: {
      privacyStatus: metadata.privacy || 'unlisted',
      selfDeclaredMadeForKids: false,
    },
  };

  const initResponse = await fetch(initUrl, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json; charset=UTF-8',
      'X-Upload-Content-Length': videoBlob.size.toString(),
      'X-Upload-Content-Type': videoBlob.type || 'video/webm',
    },
    body: JSON.stringify(bodyData),
  });

  if (!initResponse.ok) {
    const errorJson = await initResponse.json().catch(() => ({}));
    throw new Error(errorJson.error?.message || `Failed to initiate YouTube upload (${initResponse.status})`);
  }

  const uploadLocation = initResponse.headers.get('Location');
  if (!uploadLocation) {
    throw new Error('YouTube did not return a valid upload location URI.');
  }

  if (onProgress) onProgress(30);

  // Step 2: Upload the binary video blob using XMLHttpRequest for exact progress tracking
  return new Promise<{ videoId: string; watchUrl: string }>((resolve, reject) => {
    const xhr = new XMLHttpRequest();
    xhr.open('PUT', uploadLocation, true);
    xhr.setRequestHeader('Content-Type', videoBlob.type || 'video/webm');

    xhr.upload.onprogress = (event) => {
      if (event.lengthComputable && onProgress) {
        const percent = 30 + Math.round((event.loaded / event.total) * 65);
        onProgress(Math.min(95, percent));
      }
    };

    xhr.onload = () => {
      if (xhr.status >= 200 && xhr.status < 300) {
        if (onProgress) onProgress(100);
        try {
          const res = JSON.parse(xhr.responseText);
          const videoId = res.id;
          resolve({
            videoId,
            watchUrl: `https://www.youtube.com/watch?v=${videoId}`,
          });
        } catch {
          resolve({
            videoId: 'uploaded_video',
            watchUrl: 'https://youtube.com',
          });
        }
      } else {
        try {
          const errRes = JSON.parse(xhr.responseText);
          reject(new Error(errRes.error?.message || `YouTube upload failed with status ${xhr.status}`));
        } catch {
          reject(new Error(`YouTube upload failed with status ${xhr.status}: ${xhr.statusText}`));
        }
      }
    };

    xhr.onerror = () => reject(new Error('Network error during YouTube video upload.'));
    xhr.send(videoBlob);
  });
}
